-- Nomor invoice: INV/YYYYMM/001 (urut per bulan)
create or replace function public.next_invoice_no(p_tanggal date)
returns text language plpgsql security definer set search_path = public as $$
declare v_periode text := to_char(p_tanggal, 'YYYYMM'); v_n int;
begin
  insert into public.invoice_counter as c (periode, terakhir) values (v_periode, 1)
  on conflict (periode) do update set terakhir = c.terakhir + 1
  returning terakhir into v_n;
  return 'INV/' || v_periode || '/' || lpad(v_n::text, 3, '0');
end $$;

create or replace function public.trg_invoice_before_insert()
returns trigger language plpgsql as $$
begin
  if new.no_invoice is null then
    new.no_invoice := public.next_invoice_no(new.tanggal);
  end if;
  return new;
end $$;
drop trigger if exists invoice_before_insert on public.invoice;
create trigger invoice_before_insert before insert on public.invoice
  for each row execute function public.trg_invoice_before_insert();

-- Penjualan: isi harga & metode default
create or replace function public.trg_penjualan_before()
returns trigger language plpgsql as $$
begin
  if new.jenis = 'Jual' then
    if new.harga is null then
      select harga_default into new.harga from public.pengaturan where id = 1;
    end if;
    if new.metode is null then new.metode := 'Tunai'; end if;
  else
    new.harga := null; new.metode := null; new.tanggal_bayar := null; new.dp_terpakai := 0;
  end if;
  return new;
end $$;
drop trigger if exists penjualan_before on public.penjualan;
create trigger penjualan_before before insert or update on public.penjualan
  for each row execute function public.trg_penjualan_before();

-- Penjualan ke pelanggan → nota otomatis
create or replace function public.trg_penjualan_auto_nota()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if new.jenis = 'Jual' and new.pelanggan_id is not null then
    insert into public.invoice (jenis, tanggal, pelanggan_id, penjualan_id, periode_dari, periode_sampai, created_by)
    values ('Nota', new.tanggal, new.pelanggan_id, new.id, new.tanggal, new.tanggal, new.created_by);
  end if;
  return new;
end $$;
drop trigger if exists penjualan_auto_nota on public.penjualan;
create trigger penjualan_auto_nota after insert on public.penjualan
  for each row execute function public.trg_penjualan_auto_nota();

-- Nota ikut berubah kalau penjualan diedit (pelanggan / tanggal)
create or replace function public.trg_penjualan_sync_nota()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if new.jenis <> 'Jual' or new.pelanggan_id is null then
    delete from public.invoice where penjualan_id = new.id and jenis = 'Nota';
  elsif not exists (select 1 from public.invoice where penjualan_id = new.id and jenis = 'Nota') then
    insert into public.invoice (jenis, tanggal, pelanggan_id, penjualan_id, periode_dari, periode_sampai)
    values ('Nota', new.tanggal, new.pelanggan_id, new.id, new.tanggal, new.tanggal);
  else
    update public.invoice set pelanggan_id = new.pelanggan_id, periode_dari = new.tanggal, periode_sampai = new.tanggal
    where penjualan_id = new.id and jenis = 'Nota';
  end if;
  return new;
end $$;
drop trigger if exists penjualan_sync_nota on public.penjualan;
create trigger penjualan_sync_nota after update on public.penjualan
  for each row execute function public.trg_penjualan_sync_nota();

-- PO: nomor, harga default, tanggal selesai, updated_at
create or replace function public.trg_po_before()
returns trigger language plpgsql as $$
begin
  if tg_op = 'INSERT' then
    if new.no_po is null then new.no_po := 'PO-' || lpad(new.id::text, 4, '0'); end if;
  end if;
  if new.harga is null then
    select harga_default into new.harga from public.pengaturan where id = 1;
  end if;
  if new.status in ('Dikirim','Batal') and new.tanggal_selesai is null then
    new.tanggal_selesai := public.hari_ini();
  elsif new.status = 'Dipesan' then
    new.tanggal_selesai := null;
  end if;
  if tg_op = 'UPDATE' and
     (new.tanggal_pesan, new.pelanggan_id, new.tanggal_kirim, new.jumlah, new.harga, new.dp, new.status, new.catatan)
     is distinct from
     (old.tanggal_pesan, old.pelanggan_id, old.tanggal_kirim, old.jumlah, old.harga, old.dp, old.status, old.catatan) then
    new.updated_at := now();
  end if;
  return new;
end $$;
drop trigger if exists po_before on public.po;
create trigger po_before before insert or update on public.po
  for each row execute function public.trg_po_before();

-- Kirim PO: buat penjualan + tandai PO terkirim (satu langkah)
create or replace function public.kirim_po(p_po_id bigint, p_metode text default 'Tunai', p_tanggal date default null)
returns bigint language plpgsql as $$
declare v_po public.po; v_tgl date := coalesce(p_tanggal, public.hari_ini()); v_id bigint;
begin
  select * into v_po from public.po where id = p_po_id for update;
  if not found then raise exception 'PO tidak ditemukan'; end if;
  if v_po.status <> 'Dipesan' then raise exception 'PO % sudah %', v_po.no_po, v_po.status; end if;
  insert into public.penjualan (tanggal, jenis, pelanggan_id, jumlah, harga, metode, po_id, dp_terpakai, catatan)
  values (v_tgl, 'Jual', v_po.pelanggan_id, v_po.jumlah, v_po.harga, p_metode, v_po.id,
          least(v_po.dp, v_po.total), v_po.no_po)
  returning id into v_id;
  update public.po set status = 'Dikirim', tanggal_selesai = v_tgl where id = v_po.id;
  return v_id;
end $$;

