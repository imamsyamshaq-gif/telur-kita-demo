-- ---------------------------------------------------------------------
-- 6. Pre-order (PO)
--    DP masuk amplop pada tanggal_pesan.
--    Dikirim  → dibuat baris penjualan (lihat fungsi kirim_po), DP terpakai di penjualan itu.
--    Batal    → DP dikembalikan (keluar amplop) pada tanggal_selesai,
--               kecuali dp_dikembalikan = false (DP hangus = pendapatan lain).
-- ---------------------------------------------------------------------
create table if not exists public.po (
  id                       bigint generated by default as identity primary key,
  no_po                    text unique,
  tanggal_pesan            date not null default public.hari_ini(),
  pelanggan_id             bigint references public.pelanggan(id) on delete restrict,
  tanggal_kirim            date not null,
  jumlah                   int  not null check (jumlah > 0),
  harga                    numeric(12,2),
  total                    numeric(14,2) generated always as (jumlah * coalesce(harga, 0)) stored,
  dp                       numeric(14,2) not null default 0 check (dp >= 0),
  status                   text not null default 'Dipesan' check (status in ('Dipesan','Dikirim','Batal')),
  tanggal_selesai          date,
  dp_dikembalikan          boolean not null default true,
  catatan                  text,
  calendar_event_id        text,
  calendar_sisih_event_id  text,
  calendar_synced_at       timestamptz,
  created_at               timestamptz not null default now(),
  updated_at               timestamptz not null default now(),
  created_by               text default (auth.jwt() ->> 'email')
);
create index if not exists po_status_idx on public.po (status, tanggal_kirim);

