  total         numeric(14,2) generated always as
                  (case when jenis = 'Jual' then jumlah * coalesce(harga, 0) else 0 end) stored,
  metode        text check (metode in ('Tunai','Transfer','QRIS','Utang (Bayar Nanti)')),
