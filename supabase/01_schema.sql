-- =====================================================================
-- KEAMANAN (Row Level Security): hanya email di app_users yang bisa
-- membaca & mengubah data. Hak keduanya sama penuh.
-- =====================================================================
do $$
declare t text;
begin
  foreach t in array array['pengaturan','kategori_pengeluaran','pelanggan','produksi','po','penjualan',
                           'pengeluaran','aset','modal_prive','kas_opname','invoice']
  loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists akses_terdaftar on public.%I', t);
    execute format('create policy akses_terdaftar on public.%I for all to authenticated using (public.is_allowed()) with check (public.is_allowed())', t);
  end loop;
end $$;

