  dp_terpakai   numeric(14,2) not null default 0 check (dp_terpakai >= 0),
  status        text generated always as (
                  case when jenis <> 'Jual' then '-'
                       when metode = 'Utang (Bayar Nanti)' and tanggal_bayar is null then 'BELUM LUNAS'
                       else 'LUNAS' end) stored,
  catatan       text,
  created_at    timestamptz not null default now(),
  created_by    text default (auth.jwt() ->> 'email')
