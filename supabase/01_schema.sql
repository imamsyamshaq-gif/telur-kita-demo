-- =====================================================================
-- AKSES UNTUK APPS SCRIPT (backup spreadsheet + Google Calendar)
-- Apps Script memakai kunci publik (publishable / anon) + TOKEN rahasia,
-- jadi kunci rahasia Supabase tidak pernah keluar dari Supabase.
-- Buat token SEKALI di SQL Editor:   select public.buat_token_script();
-- lalu salin hasilnya ke Script Properties → SCRIPT_TOKEN.
-- Database hanya menyimpan sidik jari (sha256) token, bukan tokennya.
-- Menjalankan buat_token_script() lagi = token lama otomatis tidak berlaku.
-- =====================================================================
create table if not exists public.script_token (
  id         int primary key default 1 check (id = 1),
  token_hash text not null,
  dibuat     timestamptz not null default now()
);
alter table public.script_token enable row level security;   -- tanpa policy = tertutup untuk semua pengguna
revoke all on public.script_token from anon, authenticated;

create or replace function public.buat_token_script()
returns text language plpgsql security definer set search_path = public as $$
declare t text := replace(gen_random_uuid()::text || gen_random_uuid()::text, '-', '');
begin
  insert into public.script_token (id, token_hash) values (1, encode(sha256(convert_to(t, 'UTF8')), 'hex'))
  on conflict (id) do update set token_hash = excluded.token_hash, dibuat = now();
  return t;
end $$;

create or replace function public.cek_token_script(p_token text)
returns void language plpgsql stable security definer set search_path = public as $$
begin
  if p_token is null or length(p_token) < 32 or not exists (
       select 1 from public.script_token where token_hash = encode(sha256(convert_to(p_token, 'UTF8')), 'hex')) then
    raise exception 'Token Apps Script salah atau belum dibuat' using errcode = '42501';
  end if;
end $$;

-- Baca satu tabel/view (maks. 1000 baris per panggilan)
create or replace function public.script_ambil(p_token text, p_tabel text, p_offset int default 0, p_limit int default 1000)
returns json language plpgsql stable security definer set search_path = public as $$
declare
  urut  text := case when p_tabel = 'app_users' then 'email' else 'id' end;
  hasil json;
begin
  perform public.cek_token_script(p_token);
  if p_tabel is null or not (p_tabel = any (array['pengaturan','kategori_pengeluaran','pelanggan','produksi','penjualan',
       'v_penjualan','po','v_po','pengeluaran','v_pengeluaran','aset','modal_prive','kas_opname','invoice','v_invoice','app_users'])) then
    raise exception 'Tabel "%" tidak tersedia untuk Apps Script', p_tabel;
  end if;
  execute format('select coalesce(json_agg(t order by t.%I), ''[]''::json) from (select * from public.%I order by %I limit %s offset %s) t',
                 urut, p_tabel, urut, least(greatest(coalesce(p_limit, 1000), 1), 1000), greatest(coalesce(p_offset, 0), 0))
    into hasil;
  return hasil;
end $$;

-- Simpan ID jadwal Google Calendar milik satu PO (tidak mengubah updated_at PO)
create or replace function public.script_simpan_kalender(p_token text, p_po_id bigint, p_event_kirim text, p_event_sisih text)
returns void language plpgsql security definer set search_path = public as $$
begin
  perform public.cek_token_script(p_token);
  update public.po
     set calendar_event_id = nullif(p_event_kirim, ''), calendar_sisih_event_id = nullif(p_event_sisih, ''), calendar_synced_at = now()
   where id = p_po_id;
end $$;

-- Tanda backup terakhir (tampil di menu Pengaturan website)
create or replace function public.script_tanda_backup(p_token text)
returns void language plpgsql security definer set search_path = public as $$
begin
  perform public.cek_token_script(p_token);
  insert into public.sistem_status (kunci, nilai, updated_at)
  values ('backup_terakhir', to_char(now() at time zone 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'), now())
  on conflict (kunci) do update set nilai = excluded.nilai, updated_at = excluded.updated_at;
end $$;

